def _outcomes(run: dict[str, dict], sig: ModuleType) -> list[str]:
    """The outcomes both analyses printed, in the run's order, each one a table here names."""
    names = [list(block["outcomes"]) for block in run.values()]
    if any(order != names[0] for order in names):
        raise FiguresError("the two analyses in significance.txt print different outcomes")
    printed = [o for o in names[0] if all(b["outcomes"][o] is not None for b in run.values())]
    unlabelled = [o for o in printed if o not in (*sig.CONFIRMATORY, *SECONDARY)]
    if unlabelled:
        raise FiguresError(f"significance.txt prints outcomes no table names: {unlabelled}")
    missing = [o for o in sig.CONFIRMATORY if o not in printed]
    if missing:
        raise FiguresError(f"significance.txt does not print the main tests {missing}")
    return printed


