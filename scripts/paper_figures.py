def _load(name: str, path: Path) -> ModuleType:
    """A script as a module, once: the copy already loaded if it is this file."""
    loaded = sys.modules.get(name)
    if loaded is not None and Path(getattr(loaded, "__file__", "")).resolve() == path.resolve():
        return loaded
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module  # dataclasses look their module up here
    spec.loader.exec_module(module)
    return module


def header(what: str) -> str:
    return f"% GENERATED by scripts/paper_figures.py. Do not edit by hand.\n% {what}\n"


def latex_text(text: str) -> str:
    """Plain text, such as a survey statement, as LaTeX."""
    special = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    escaped = "".join(special.get(char, char) for char in text)
    return re.sub(r'"([^"]*)"', r"``\1''", escaped)


def coordinate(x: float) -> str:
    """A number for pgfplots: no exponent, no trailing zeros."""
    if not math.isfinite(x):
        raise FiguresError(f"cannot draw {x}")
    text = f"{x:.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


class Cite:
    """`\\stat{key}` for a key numbers.tex defines; any other key stops the build here, not in
    LaTeX."""

    def __init__(self, defined: dict[str, str]) -> None:
        self.defined = defined
        self.used: set[str] = set()

    def __call__(self, key: str) -> str:
        if key not in self.defined:
            raise FiguresError(f"paper/numbers.tex defines no {key}")
        self.used.add(key)
        return rf"\stat{{{key}}}"

    def value(self, key: str) -> str:
        self(key)
        return self.defined[key]


def check_palette() -> None:
    """The colours drawn, held to the app's floors (CLAUDE.md, Accessibility baseline)."""
    floors = {
        "staticcolour": contrast.GRAPHIC_MIN,
        "interactivecolour": contrast.GRAPHIC_MIN,
        "inkcolour": contrast.TEXT_MIN,
        "axiscolour": contrast.TEXT_MIN,
    }
    for name, floor in floors.items():
        ratio = contrast.contrast_ratio(COLOURS[name], WHITE)
        if ratio < floor:
            raise FiguresError(f"{name} {COLOURS[name]} is {ratio:.2f}:1 on white, under {floor}")
    apart = contrast.cvd_distance(COLOURS["staticcolour"], COLOURS["interactivecolour"])
    if apart < config.MIN_CVD_DISTANCE:
        raise FiguresError(f"the two versions' colours are {apart:.1f} apart in CIEDE2000")


