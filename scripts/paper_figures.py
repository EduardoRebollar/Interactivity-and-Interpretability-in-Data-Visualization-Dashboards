def exclusions_table(cite: Cite, analyses: dict, prefix: dict) -> str:
    """Table: each pre-registered exclusion rule, in the order it runs, for both analyses."""
    labels = _exclusion_labels(cite)
    rules = {name: [e.rule for e in analyses[name].exclusions] for name in prefix}
    order = rules["main"]
