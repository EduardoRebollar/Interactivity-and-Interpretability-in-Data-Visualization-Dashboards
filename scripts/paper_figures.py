def accuracy_figure(outputs: dict, run: dict[str, dict], sig: ModuleType) -> str:
    """Figure: each participant's accuracy difference in items (main analysis), with each
    analysis's estimate, its 95% and 90% CIs, and the band of one item either way."""
    items = sig.ITEMS_PER_CONDITION
    diffs = outputs["differences_by_participant.csv"]
    mine = diffs[(diffs["analysis"] == "main") & (diffs["outcome"] == "accuracy")]
    counts = stacked(mine["d"].astype(float) * items, "accuracy")
    estimates = [
        Estimate(
            _row_label(name, block["outcomes"]["accuracy"]["n"]),
            float(block["lines"]["items"]["est"]),
            _ci(block["lines"]["items"]),
            _ci(block["lines"]["tost"], items),
        )
        for name, block in run.items()
    ]
    bound = sig.EQUIVALENCE_BOUND * items
    return header(
        "Each participant's accuracy difference in items (main analysis), as a count per value;"
        " each analysis's estimate with its 95% (thin) and 90% (thick) CIs."
    ) + dot_plot(
        counts,
        estimates,
        f"Items correct, interactive minus static (of {items})",
        band=bound,
    )


def effort_figure(outputs: dict, run: dict[str, dict]) -> str:
    """Figure: each participant's change in Paas and in a7 (main analysis), Paas with each
    analysis's estimate and 95% CI. a7 is descriptive, so it has no interval."""
    pairs = outputs["paas_a7_pairs.csv"]
    mine = pairs[pairs["analysis"] == "main"]
    wide = mine.pivot(index="participant_id", columns="condition", values=["paas", "a7"])
    changes = {
        measure: (wide[measure]["interactive"] - wide[measure]["static"]).dropna()
        for measure in ("paas", "a7")
    }
    reach = max(float(change.abs().max()) for change in changes.values())
    plots = []
    for measure, title in (("paas", "Paas mental effort"), ("a7", "a7 agreement")):
        counts = stacked(changes[measure], measure)
        estimates = (
            [
                Estimate(
                    _row_label(name, block["outcomes"]["paas"]["n"]),
                    float(block["outcomes"]["paas"]["effect"]),
                    _ci(block["outcomes"]["paas"]),
                )
                for name, block in run.items()
            ]
            if measure == "paas"
            else []
        )
        plots.append(
            dot_plot(counts, estimates, f"{title}: interactive minus static (points)", reach=reach)
        )
    return (
        header(
            "Each participant's change in Paas and in a7 (main analysis), as a count per value;"
            " Paas with each analysis's estimate and 95% CI. a7 is descriptive: no interval."
        )
        + plots[0]
        + "\n\\medskip\n\n"
        + plots[1]
    )


TIME_TICKS = (0.25, 0.33, 0.5, 0.67, 1, 1.5, 2, 3, 4)


def time_figure(outputs: dict, run: dict[str, dict]) -> str:
    """Figure: each participant's time ratio (main analysis), sorted, on a log scale, with each
    analysis's estimate and 95% CI. Exploratory."""
    diffs = outputs["differences_by_participant.csv"]
    mine = diffs[(diffs["analysis"] == "main") & (diffs["outcome"] == "log_time")]
    ratios = sorted(math.exp(float(d)) for d in mine["d"])
    estimates = [
        Estimate(
            _row_label(name, block["outcomes"]["log_time"]["n"]),
            float(block["outcomes"]["log_time"]["effect"].lstrip("x")),
            _ci(block["outcomes"]["log_time"]),
        )
        for name, block in run.items()
    ]
    unit_pt = 3.2
    rows = _rows(len(estimates), unit_pt)
    bottom, top = _bottom(rows, unit_pt), len(ratios) + 0.8
    low = min(ratios + [e.ci95[0] for e in estimates]) / 1.1
    high = max(ratios + [e.ci95[1] for e in estimates]) * 1.1
    ticks = [t for t in TIME_TICKS if low <= t <= high]
    lines = [
        header(
            "Exploratory. Each participant's time ratio, interactive to static (main analysis),"
            " sorted by value; each analysis's estimate and 95% CI."
        ),
        r"\begin{tikzpicture}",
        r"\begin{axis}[",
        r"  paper dots,",
        r"  xmode=log,",
        f"  y={coordinate(unit_pt)}pt,",
        f"  xmin={coordinate(low)}, xmax={coordinate(high)},",
        f"  ymin={coordinate(bottom)}, ymax={coordinate(top)},",
        f"  xtick={{{','.join(coordinate(t) for t in ticks)}}},",
        f"  xticklabels={{{','.join(coordinate(t) for t in ticks)}}},",
        r"  minor xtick={},",
        r"  xlabel={Time per item, interactive $\div$ static (log scale)},",
        "]",
        rf"\draw[axiscolour] (axis cs:1,{coordinate(bottom)}) -- (axis cs:1,{coordinate(top)});",
        r"\addplot[only marks, mark=*, mark size=1.5pt, inkcolour] coordinates {"
        + " ".join(f"({coordinate(r)},{k})" for k, r in enumerate(ratios, start=1))
        + "};",
        *_estimate_rows(estimates, rows, unit_pt, low),
        r"\end{axis}",
        r"\end{tikzpicture}",
    ]
    return "\n".join(lines) + "\n"


def items_figure(analysis) -> str:
    """Figure: accuracy by item and version (main analysis), as dots, T1 at the top, the versions
    a little apart so equal values stay visible."""
    by_item = study_report.by_item(analysis.tasks)
    correct = {
        (task, condition): float(row["correct"]) * 100
        for (task, _chart, _kind, condition), row in by_item.iterrows()
    }
    items = _items()
    offsets = {"static": 0.15, "interactive": -0.15}
    styles = {
        "static": "mark=*, mark size=2.2pt, staticcolour",
        "interactive": "mark=square*, mark size=2pt, interactivecolour",
    }
    # T1 at the top: item k sits at y = len - k + 1.
    labels = ",".join(f"{{{task} {chart}}}" for task, chart in reversed(items))
    lines = [
        header("Accuracy by item and version (main analysis)."),
        r"\begin{tikzpicture}",
        r"\begin{axis}[",
        r"  paper,",
        r"  width=\linewidth-56pt,",
        r"  y=13pt,",
        r"  xmin=-2, xmax=102, xtick={0,20,...,100},",
        f"  ymin=0.4, ymax={len(items) + 0.6},",
        f"  ytick={{1,...,{len(items)}}},",
        f"  yticklabels={{{labels}}},",
        r"  ytick style={draw=none},",
        r"  xmajorgrids, grid style={gridcolour},",
        r"  xlabel={Correct (\%)},",
        r"  legend style={at={(0.5,1.03)}, anchor=south,"
        r" /tikz/every even column/.append style={column sep=8pt}}, legend columns=2,",
        "]",
    ]
    for condition in CONDITIONS:
        points = " ".join(
            f"({coordinate(correct[(task, condition)])},"
            f"{coordinate(len(items) - k + 1 + offsets[condition])})"
            for k, (task, _chart) in enumerate(items, start=1)
        )
        lines.append(rf"\addplot[only marks, {styles[condition]}] coordinates {{{points}}};")
        lines.append(rf"\addlegendentry{{{condition.capitalize()}}}")
    lines += [r"\end{axis}", r"\end{tikzpicture}"]
    return "\n".join(lines) + "\n"


# --- Figure 1: one item in both versions ---------------------------------------------------------
def versions_html(questionnaire: ModuleType) -> str:
    """A-T6's task screen in each version, one per page, drawn by the questionnaire's renderer from
    the app's own screen code. When Plotly has drawn both charts, a script writes where each card
    and its chart column sit on the body's `data-crops`."""
    from plotly.offline import get_plotlyjs

    items = study_tasks.for_form(VERSIONS_FORM)
    index, task = next((i, t) for i, t in enumerate(items, 1) if t.task_id == VERSIONS_ITEM)
    renderer = questionnaire.Renderer()
    sections = "".join(
        f'<section data-version="{version}"><div class="screen">'
        + renderer.render(
            study_layout.task_screen(task, interactive, index=index, total=len(items))
        )
        + "</div></section>"
        for version, interactive in VERSIONS
    )
    app_css = "\n".join(sheet.read_text(encoding="utf-8") for sheet in questionnaire.STYLESHEETS)
    width, height = PAGE_PX
    page = (
        f"@page {{ size: {width}px {height}px; margin: 0; }}\n"
        f".screen {{ zoom: 1; width: {width}px; border: none; border-radius: 0; }}\n"
        "section:first-of-type { break-before: auto; }\n"
    )
    payload = json.dumps(renderer.figures).replace("</", "<\\/")
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>Figure 1</title>
<style>{app_css}</style>
<style>{questionnaire.STYLE}</style>
<style>{page}</style>
</head><body>
{sections}
<script>{get_plotlyjs()}</script>
<script type="application/json" id="figures">{payload}</script>
<script>
var figures = JSON.parse(document.getElementById("figures").textContent);
var drawn = [];
document.querySelectorAll(".chart").forEach(function (div) {{
  var figure = JSON.parse(figures[Number(div.dataset.figure)]);
  drawn.push(Plotly.newPlot(div, figure.data, figure.layout, {{staticPlot: true}}));
}});
Promise.all(drawn).then(function () {{
  var crops = [];
  document.querySelectorAll("section").forEach(function (section) {{
    var base = section.getBoundingClientRect();
    var card = section.querySelector(".ui-card--task").getBoundingClientRect();
    var column = section.querySelector(".ui-main").getBoundingClientRect();
    crops.push({{version: section.dataset.version, x: card.left - base.left,
                 y: card.top - base.top, w: column.right - card.left,
                 h: card.bottom - card.top, section: base.height}});
  }});
  document.body.setAttribute("data-crops", JSON.stringify(crops));
}});
</script>
</body></html>
"""


def _browse(browser: str, arguments: list[str]) -> bytes:
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as profile:
        done = subprocess.run(
            [
                browser,
                "--headless=new",
                "--disable-gpu",
                f"--user-data-dir={profile}",
                "--virtual-time-budget=30000",
                *arguments,
            ],
            check=True,
            capture_output=True,
            timeout=180,
        )
    return done.stdout


def read_crops(dom: str) -> list[dict]:
    """The crops the page's script wrote, from Chrome's dump of the drawn page."""
    found = re.search(r'data-crops="([^"]*)"', dom)
    if found is None:
        raise FiguresError("the page did not measure its cards: did Plotly draw?")
    crops = json.loads(html.unescape(found[1]))
    if [c["version"] for c in crops] != [version for version, _ in VERSIONS]:
        raise FiguresError(f"measured {len(crops)} screens, not one per version")
    for crop in crops:
        if crop["section"] > PAGE_PX[1] or min(crop["w"], crop["h"]) <= 0:
            raise FiguresError(f"the {crop['version']} screen does not fit one page")
    return crops


def page_boxes(pdf: bytes) -> list[tuple[float, float]]:
    return [(float(w), float(h)) for w, h in MEDIA_BOX.findall(pdf)]


def trims(crop: dict, page: tuple[float, float]) -> tuple[float, float, float, float]:
    """graphicx's trim (left, bottom, right, top) in PDF points, keeping only `crop` (CSS px)."""
    width, height = page
    left, top = crop["x"] * PX_TO_BP, crop["y"] * PX_TO_BP
    right = width - (crop["x"] + crop["w"]) * PX_TO_BP
    bottom = height - (crop["y"] + crop["h"]) * PX_TO_BP
    if min(left, top, right, bottom) < 0:
        raise FiguresError(f"the {crop['version']} card runs off its page")
    return tuple(round(x, 2) for x in (left, bottom, right, top))


def versions_tex(crops: list[dict], pages: list[tuple[float, float]]) -> str:
    lines = [
        header(
            f"Figure 1: item {VERSIONS_FORM}-{VERSIONS_ITEM} in both versions, cropped to the"
            " chart's card (figures/versions.pdf, printed by headless Chrome from the app's"
            " screen code)."
        ),
        r"\setlength{\fboxsep}{0pt}%",
    ]
    for number, (crop, page) in enumerate(zip(crops, pages, strict=True), start=1):
        trim = " ".join(f"{x:g}bp" for x in trims(crop, page))
        lines += [
            rf"{{\footnotesize\textbf{{{crop['version'].capitalize()}}}}}\\[2pt]",
            rf"\fcolorbox{{gridcolour}}{{white}}{{\includegraphics[page={number}, trim={trim},"
            r" clip, width=\dimexpr\linewidth-2\fboxrule\relax]{figures/versions.pdf}}"
            + (r"\\[6pt]" if number < len(crops) else ""),
        ]
    return "\n".join(lines) + "\n"


def draw_versions(browser: str, out: Path, questionnaire: ModuleType) -> dict[str, str]:
    """Figure 1: prints figures/versions.pdf and returns figures/versions.tex's text."""
    figures_dir = out / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as work:
        page = Path(work) / "versions.html"
        page.write_text(versions_html(questionnaire), encoding="utf-8")
        width, height = PAGE_PX
        dom = _browse(browser, [f"--window-size={width},{height}", "--dump-dom", page.as_uri()])
        crops = read_crops(dom.decode("utf-8", errors="replace"))
        pdf = figures_dir / "versions.pdf"
        questionnaire.print_pdf(browser, page, pdf)
    pages = page_boxes(pdf.read_bytes())
    if len(pages) != len(VERSIONS):
        raise FiguresError(f"{pdf} has {len(pages)} pages, not one per version")
    for found in pages:
        if abs(found[0] - width * PX_TO_BP) > 1:
            raise FiguresError(f"{pdf} printed {found[0]} points wide, not {width * PX_TO_BP}")
    return {"figures/versions.tex": versions_tex(crops, pages)}


# --- Assembling and writing -----------------------------------------------------------------------
def build(inputs, sig: ModuleType, pdesc: ModuleType, pnum: ModuleType, numbers_tex: str) -> dict:
    """Every table and Figures 2 to 5, as {path under paper/: text}, once every check passes."""
    check_palette()
    analyses = pdesc.build_analyses(inputs, sig)
    outputs = pdesc.build(inputs, sig)
    numbers = pnum.build_numbers(inputs, sig, pdesc, outputs=outputs, analyses=analyses)
    if pnum.render(numbers) != numbers_tex:
        raise FiguresError(
            "paper/numbers.tex is not what scripts/paper_numbers.py writes from these files: "
            "run it first"
        )
    cite, run, prefix = Cite(numbers.values), inputs.significance, pnum.PREFIX
    main, pre = (prefix[name] for name in ("main", "preregistered"))
    return {
        "tables/tests.tex": tests_table(cite, run, sig, prefix),
        "tables/secondary.tex": secondary_table(cite, run, sig, prefix),
        "tables/exclusions.tex": exclusions_table(cite, analyses, prefix),
        "tables/items.tex": items_table(cite, main, "main analysis"),
        "tables/items-pre.tex": items_table(cite, pre, "as pre-registered"),
        "tables/survey.tex": survey_table(cite, main, "main analysis"),
        "tables/survey-pre.tex": survey_table(cite, pre, "as pre-registered"),
        "figures/style.tex": style_tex(),
        "figures/accuracy.tex": accuracy_figure(outputs, run, sig),
        "figures/effort.tex": effort_figure(outputs, run),
        "figures/items.tex": items_figure(analyses["main"]),
        "figures/time.tex": time_figure(outputs, run),
    }


def write(files: dict[str, str], out: Path) -> None:
    for relative, text in files.items():
        path = out / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {path}")


def main(argv: list[str] | None = None) -> int:
    pnum = _load("paper_numbers", NUMBERS_SCRIPT)
    pdesc = pnum.load_descriptives()
    parser = argparse.ArgumentParser(description="Write paper/tables/ and paper/figures/.")
    parser.add_argument("--derived", type=Path, default=pdesc.DERIVED)
    parser.add_argument("--coding", type=Path, default=pdesc.CODING)
    parser.add_argument("--significance", type=Path, help="default: DERIVED/significance.txt")
    parser.add_argument("--rules", type=Path, default=pdesc.GRADING_RULES)
    parser.add_argument("--numbers", type=Path, default=OUT / "numbers.tex")
    parser.add_argument("--out", type=Path, default=OUT, help="the paper's folder")
    parser.add_argument("--browser", help="path to Chrome, Chromium or Edge, for Figure 1")
    parser.add_argument("--no-browser", action="store_true", help="keep Figure 1 as it is")
    parser.add_argument("--versions-only", action="store_true", help="Figure 1 alone; no data")
    args = parser.parse_args(argv)

    if not args.versions_only:
        sig = pdesc.load_notebook()
        try:
            if not args.numbers.exists():
                raise FiguresError(f"{args.numbers} is missing: run scripts/paper_numbers.py")
            inputs = pdesc.load_inputs(
                args.derived,
                args.coding,
                args.significance or args.derived / "significance.txt",
                args.rules,
                sig.LABELS,
            )
            files = build(inputs, sig, pdesc, pnum, args.numbers.read_text(encoding="utf-8"))
        except (
            pdesc.PaperError,
            sig.PlanError,
            coding.CodingError,
            pnum.NumbersError,
            FiguresError,
        ) as exc:
            print(f"Refusing to write: {exc}", file=sys.stderr)
            return 1
        write(files, args.out)
    if args.no_browser:
        return 0

    questionnaire = _load("export_questionnaire", QUESTIONNAIRE)
    browser = questionnaire.find_browser(args.browser)
    if browser is None:
        print("No Chrome or Edge for Figure 1: pass --browser, or --no-browser.", file=sys.stderr)
        return 1
    try:
        write(draw_versions(browser, args.out, questionnaire), args.out)
    except (subprocess.SubprocessError, OSError, RuntimeError) as exc:
        print(f"Figure 1 failed: {exc}", file=sys.stderr)
        return 1
    print(f"Wrote {args.out / 'figures' / 'versions.pdf'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
